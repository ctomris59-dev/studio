const assert=require("node:assert/strict"),fs=require("node:fs"),ts=require("typescript");
const source=fs.readFileSync("lib/demo-auth.ts","utf8"),compiled={exports:{}};
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
new Function("module","exports",js)(compiled,compiled.exports);
const {DEMO_ACCOUNT,authenticateDemo}=compiled.exports;
assert.equal(authenticateDemo(DEMO_ACCOUNT.email,DEMO_ACCOUNT.password),true);
assert.equal(authenticateDemo("  OWNER@DEMO.STUDIOTASKER.COM  ",DEMO_ACCOUNT.password),true);
assert.equal(authenticateDemo(DEMO_ACCOUNT.email,"wrong"),false);
assert.equal(authenticateDemo("member@demo.studiotasker.com","MemberDemo!"),false);
console.log("Owner-only app demo authentication checks passed.");
